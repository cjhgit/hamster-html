// Mechanical AS2 → JavaScript conversion. Original decompiled sources are kept
// under analysis/scripts so behavior and geometry remain auditable.
import fs from 'node:fs';
const base = 'analysis/scripts/';
const files = ['__Packages/com/abowman/math/Trig.as','__Packages/com/abowman/graphics/Draw.as','__Packages/HamsterPart.as','__Packages/LegV2.as','__Packages/Food.as','__Packages/WaterBottle.as','__Packages/Hamster.as'];
let output = '// Generated by scripts/build-port.mjs from the supplied hamster.swf.\n';
for (const file of files) {
  let s = fs.readFileSync(base + file,'utf8').replace(/\r/g,'');
  const fullName = s.match(/^class ([\w.]+)/)[1];
  const name = fullName.split('.').pop();
  s = s.replace(/^class [\w.]+/, `class ${name}`)
    .replace(/^   (static )?var /gm, '   $1')
    .replace(/\b(static )?function (\w+)\(/g, (_, stat='', method) => `${stat}${method === name ? 'constructor' : method}(`)
    .replace(/Object\.registerClass\(/g, 'registerClass(')
    .replace(/\b(?:Food|WaterBottle|MovieClip)\(([^;\n]+)\)/g, 'identity($1)');
  // AVM1 silently ignores a method call on an undefined optional drawing clip.
  if(name === 'LegV2') s = s.replace(/mcBG\.(moveTo|lineTo)\(/g,'mcBG?.$1(');
  output += s + '\n';
  if (fullName.includes('.')) output += `${fullName} = ${name};\n`;
}
let root = fs.readFileSync(base + 'frame_1/DoAction.as','utf8').replace(/\r/g,'');
root = root.replace(/^function (\w+)\(/gm,'this.$1 = function(');
// Root timeline variables belong to its MovieClip scope, not a JS stack frame.
root = root.replace(/^var (\w+)([^\n]*)/gm,(_,name,rest) => `this.${name}${rest === ';' ? ' = undefined;' : rest}`);
root = root.replace(/MovieClip\(eatenFood.pop\(\)\)/g,'identity(eatenFood.pop())');
root = root.replace('food.drag = false;', 'if (food) food.drag = false;');
// AS2 hoists timeline functions before executing its first frame.
output += '\nfunction initializeTimeline(root) {\nwith(root) {\n' + root + '\n}\n}\n';
fs.mkdirSync('src',{recursive:true});
fs.writeFileSync('src/original.js',output);
console.log('Generated src/original.js from all 8 ActionScript scripts.');
